#!/usr/bin/env bash
# Write the AUR `pergola-bin` package files for one release.
#
#   scripts/gen-bin-pkgbuild.sh <version> <x86_64-tarball> <aarch64-tarball> <out-dir>
#
# Writes <out-dir>/PKGBUILD and <out-dir>/pergola.install. The sums are read from
# the tarballs, so the generated package always matches the bytes it points at.
# CI runs this on the files it is about to attach and attaches both files to the
# release; locally it is how the package is tested:
#
#   scripts/make-release-artifacts.sh 1.0.0 x86_64 target/release/pergola /tmp/dist
#   scripts/gen-bin-pkgbuild.sh 1.0.0 /tmp/dist/pergola-1.0.0-x86_64-linux-gnu.tar.gz \
#       /tmp/dist/pergola-1.0.0-aarch64-linux-gnu.tar.gz /tmp/aur
#   cd /tmp/aur && makepkg -f
#
# A version with a `-` (a `-dev` build) is refused: pacman's pkgver cannot carry
# one, and tagging a dev build is against docs/VERSIONING.md.
set -euo pipefail

usage() { sed -n '2,17p' "$0"; exit 2; }
[ $# -eq 4 ] || usage
VERSION="$1"
X86="$2"
ARM="$3"
OUT="$4"

case "$VERSION" in
  *-*) echo "gen-bin-pkgbuild: '$VERSION' is a dev version; release only a stable tag" >&2; exit 1 ;;
  *) ;;
esac
for f in "$X86" "$ARM"; do
  [ -f "$f" ] || { echo "gen-bin-pkgbuild: no such tarball: $f" >&2; exit 1; }
done

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
mkdir -p "$OUT"

SUMS_X86="$(sha256sum "$X86" | awk '{print $1}')"
SUMS_ARM="$(sha256sum "$ARM" | awk '{print $1}')"

cat > "$OUT/PKGBUILD" <<'PKGBUILD'
# Maintainer: SyntheticPrometheus <syntheticprometheus@users.noreply.github.com>
#
# pergola-bin — prebuilt Pergola from a GitHub release.
#
# Generated by `scripts/gen-bin-pkgbuild.sh` at release time, so the checksums
# are those of the artifacts attached to the tag. The file list is identical to
# pergola-git's; only the build step disappears.
pkgname=pergola-bin
pkgver=@VERSION@
pkgrel=1
pkgdesc='Fractal window manager layer for X11 desktops (prebuilt)'
arch=('x86_64' 'aarch64')
url='https://github.com/SyntheticPrometheus/pergola'
license=('MIT')
depends=('glibc' 'gcc-libs')
optdepends=(
  'rofi: action palette (recommended)'
  'dmenu: action palette'
  'zenity: action palette'
  'yad: action palette'
)
provides=('pergola')
conflicts=('pergola' 'pergola-git')
install=pergola.install
# The release build is already stripped; pacman's strip step only complains
# about the missing symbols, and an empty -debug package is noise.
options=('!strip' '!debug')
source_x86_64=("https://github.com/SyntheticPrometheus/pergola/releases/download/v@VERSION@/pergola-@VERSION@-x86_64-linux-gnu.tar.gz")
source_aarch64=("https://github.com/SyntheticPrometheus/pergola/releases/download/v@VERSION@/pergola-@VERSION@-aarch64-linux-gnu.tar.gz")
sha256sums_x86_64=('@SUMS_X86@')
sha256sums_aarch64=('@SUMS_ARM@')

package() {
  cd "pergola-@VERSION@-$CARCH-linux-gnu"

  install -Dm755 pergola "$pkgdir/usr/bin/pergola"
  install -Dm755 pergola-health "$pkgdir/usr/bin/pergola-health"

  # Session files: system paths, and no hard-coded display (the packaged unit
  # inherits DISPLAY from the graphical session).
  install -Dm644 systemd/pergola.service "$pkgdir/usr/lib/systemd/user/pergola.service"
  sed -i \
    -e 's|%h/\.local/bin/pergola|/usr/bin/pergola|' \
    -e '/^Environment=DISPLAY=/d' \
    "$pkgdir/usr/lib/systemd/user/pergola.service"
  install -Dm644 autostart/pergola.desktop "$pkgdir/usr/share/xdg/autostart/pergola.desktop"
  sed -i 's|%h/\.local/bin/pergola|/usr/bin/pergola|' \
    "$pkgdir/usr/share/xdg/autostart/pergola.desktop"
  install -Dm644 desktop/pergola-actions.desktop "$pkgdir/usr/share/applications/pergola-actions.desktop"
  sed -i 's|%h/\.local/bin/pergola|/usr/bin/pergola|g' \
    "$pkgdir/usr/share/applications/pergola-actions.desktop"

  install -Dm644 LICENSE "$pkgdir/usr/share/licenses/$pkgname/LICENSE"
  install -Dm644 NOTICE "$pkgdir/usr/share/licenses/$pkgname/NOTICE"
  install -Dm644 README.md "$pkgdir/usr/share/doc/$pkgname/README.md"
  install -Dm644 docs/SETUP.md "$pkgdir/usr/share/doc/$pkgname/SETUP.md"
  install -Dm644 docs/FIRST-RUN.md "$pkgdir/usr/share/doc/$pkgname/FIRST-RUN.md"
  install -Dm644 docs/UX-NOTES.md "$pkgdir/usr/share/doc/$pkgname/UX-NOTES.md"
  install -Dm644 docs/HISTORY-LESSONS.md "$pkgdir/usr/share/doc/$pkgname/HISTORY-LESSONS.md"
  install -Dm644 config.json "$pkgdir/usr/share/doc/$pkgname/config.json"
}
PKGBUILD

sed -i -e "s|@VERSION@|$VERSION|g" \
  -e "s|@SUMS_X86@|$SUMS_X86|" \
  -e "s|@SUMS_ARM@|$SUMS_ARM|" \
  "$OUT/PKGBUILD"

# The scriptlet is the pergola-git one, with the package name in the paths it
# prints. Keeping one file means the two packages cannot drift apart.
sed 's/pergola-git/pergola-bin/g' "$ROOT/packaging/aur/pergola.install" > "$OUT/pergola.install"

printf '%s\n' "$OUT/PKGBUILD" "$OUT/pergola.install"
